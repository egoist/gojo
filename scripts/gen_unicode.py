#!/usr/bin/env python3
# Generates runtime/gojo_unicode.c, the Unicode tables behind the `rune`
# methods (`isLetter`, `toUpper`...), `str.toUpper`/`toLower` and
# `str.equalFold`, from the Unicode Character Database.
#
#   python3 scripts/gen_unicode.py [UCD directory]
#
# Without a directory it downloads the files of the version below into a
# temporary directory.
import os
import sys
import tempfile
import urllib.request

VERSION = "16.0.0"
FILES = ["UnicodeData.txt", "PropList.txt", "CaseFolding.txt"]

LETTER, UPPER, LOWER, DIGIT, NUMBER, PUNCT, SPACE, CONTROL, SYMBOL, MARK = (1 << i for i in range(10))


def ucd_dir():
    if len(sys.argv) > 1:
        return sys.argv[1]
    d = tempfile.mkdtemp()
    for f in FILES:
        urllib.request.urlretrieve(f"https://www.unicode.org/Public/{VERSION}/ucd/{f}", os.path.join(d, f))
    return d


def lines(path):
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if line:
                yield [x.strip() for x in line.split(";")]


def main():
    d = ucd_dir()
    props = {}
    upper, lower = {}, {}
    first = None
    for f in lines(os.path.join(d, "UnicodeData.txt")):
        cp, name, cat = int(f[0], 16), f[1], f[2]
        bits = 0
        if cat[0] == "L":
            bits |= LETTER
        if cat == "Lu":
            bits |= UPPER
        if cat == "Ll":
            bits |= LOWER
        if cat == "Nd":
            bits |= DIGIT
        if cat[0] == "N":
            bits |= NUMBER
        if cat[0] == "P":
            bits |= PUNCT
        if cat == "Cc":
            bits |= CONTROL
        if cat[0] == "S":
            bits |= SYMBOL
        if cat[0] == "M":
            bits |= MARK
        # ranges: <CJK Ideograph, First> ... <..., Last>
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            for c in range(first, cp + 1):
                props[c] = bits
            continue
        props[cp] = bits
        if f[12]:
            upper[cp] = int(f[12], 16)
        if f[13]:
            lower[cp] = int(f[13], 16)
    for f in lines(os.path.join(d, "PropList.txt")):
        if f[1] != "White_Space":
            continue
        lo, _, hi = f[0].partition("..")
        for c in range(int(lo, 16), int(hi or lo, 16) + 1):
            props[c] = props.get(c, 0) | SPACE
    fold = {}
    for f in lines(os.path.join(d, "CaseFolding.txt")):
        if f[1] in ("C", "S"):
            fold[int(f[0], 16)] = int(f[2], 16)

    # property ranges: runs of code points with the same bits
    ranges = []
    for c in sorted(props):
        b = props[c]
        if b == 0:
            continue
        if ranges and ranges[-1][1] == c - 1 and ranges[-1][2] == b:
            ranges[-1][1] = c
        else:
            ranges.append([c, c, b])

    # mappings: runs of code points, `stride` apart, that all move by `delta`
    def runs(m):
        out = []
        for c in sorted(m):
            delta = m[c] - c
            if out:
                lo, hi, stride, dl = out[-1]
                if dl == delta and (stride == 0 and c - hi <= 2 or stride and c - hi == stride):
                    out[-1] = [lo, c, c - hi, dl]
                    continue
            out.append([c, c, 0, delta])
        return out

    w = []
    w.append(f"// Generated by scripts/gen_unicode.py from the Unicode {VERSION} Character")
    w.append("// Database. Do not edit.")
    w.append("")
    w.append("typedef struct { uint32_t lo, hi; uint16_t bits; } gojo_uprop;")
    w.append("typedef struct { int32_t lo, hi, stride, delta; } gojo_umap;")
    w.append("")
    w.append(f"static const gojo_uprop gojo_uprops[{len(ranges)}] = {{")
    for lo, hi, b in ranges:
        w.append(f"    {{0x{lo:X}, 0x{hi:X}, {b}}},")
    w.append("};")
    for name, m in (("upper", upper), ("lower", lower), ("fold", fold)):
        rs = runs(m)
        w.append("")
        w.append(f"static const gojo_umap gojo_u{name}[{len(rs)}] = {{")
        for lo, hi, stride, delta in rs:
            w.append(f"    {{0x{lo:X}, 0x{hi:X}, {stride or 1}, {delta}}},")
        w.append("};")
    w.append("")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "runtime", "gojo_unicode.c")
    with open(out, "w") as fh:
        fh.write("\n".join(w))
    print(f"{len(ranges)} property ranges, {len(runs(upper))}/{len(runs(lower))}/{len(runs(fold))} mapping runs")


main()
