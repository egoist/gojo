    fn arg_vals(&mut self, fs: &mut Fs, args: &[TArg]) -> Vec<String> {
        let tys: Vec<Ty> = args.iter().map(|a| self.sub(fs, &a.e.ty)).collect();
        let modes: Vec<Mode> = args.iter().map(|a| match a.mode {
            ArgMode::Borrow => Mode::Borrow,
            ArgMode::Inout => Mode::Inout,
            ArgMode::Value => Mode::Sink,
        }).collect();
        self.args(fs, args, &modes, &tys)
    }

    fn magic(&mut self, fs: &mut Fs, name: &str, targs: &[Ty], args: &[TArg], t: &Ty, sp: Span) -> String {
        let l = self.loc(sp);
        match name {
            "len" => {
                let at = self.sub(fs, &args[0].e.ty);
                match &at {
                    Ty::Array(_, n) => n.to_string(),
                    _ => {
                        let p = self.lval(fs, &args[0].e);
                        format!("((int64_t){}.len)", p)
                    }
                }
            }
            "clone" => {
                let at = self.sub(fs, &args[0].e.ty);
                if self.is_copy(&at) {
                    return self.expr(fs, &args[0].e);
                }
                let p = self.addr(fs, &args[0].e);
                let f = self.clone_fn(&at);
                format!("{}({})", f, p)
            }
            "str_concat" => {
                let a = self.expr(fs, &args[0].e);
                let a = self.materialize(fs, &a, &Ty::Str, false);
                let b = self.expr(fs, &args[1].e);
                let r = self.tmp();
                self.emit(fs, &format!("kite_string {} = kite_str_concat({}, {});", r, a, b));
                r
            }
            "str_to_string" => {
                let a = self.expr(fs, &args[0].e);
                format!("kite_string_from({})", a)
            }
            "rune_to_string" => {
                let a = self.expr(fs, &args[0].e);
                format!("kite_rune_to_string({})", a)
            }
            "bytes_to_string" => {
                let a = self.expr(fs, &args[0].e);
                let s = self.tmp();
                self.emit(fs, &format!("kite_slice {} = {};", s, a));
                format!("kite_string_from((kite_str){{ (const uint8_t *){}.ptr, {}.len }})", s, s)
            }
            "fmt.print" | "fmt.println" | "fmt.eprint" | "fmt.eprintln" | "fmt.sprint" | "fmt.sprintln" => {
                let b = self.tmp();
                self.emit(fs, &format!("kite_string {} = {{0}};", b));
                for (i, a) in args.iter().enumerate() {
                    let at = self.sub(fs, &a.e.ty);
                    if i > 0 {
                        self.emit(fs, &format!("kite_string_push_byte(&{}, ' ');", b));
                    }
                    let p = self.addr(fs, &a.e);
                    let f = self.fmt_fn(&at);
                    self.emit(fs, &format!("{}(&{}, {}, 0);", f, b, p));
                }
                if name.ends_with("ln") {
                    self.emit(fs, &format!("kite_string_push_byte(&{}, '\\n');", b));
                }
                match name {
                    "fmt.sprint" | "fmt.sprintln" => b,
                    "fmt.eprint" | "fmt.eprintln" => {
                        self.emit(fs, &format!("kite_write(2, &{});", b));
                        "0".into()
                    }
                    _ => {
                        self.emit(fs, &format!("kite_write(1, &{});", b));
                        "0".into()
                    }
                }
            }
            "task.group" => self.task_group(fs, targs, args, t, sp),
            "task.go" => {
                let _ = l;
                self.task_go(fs, args, sp)
            }
            _ => panic!("unknown intrinsic {}", name),
        }
    }

    fn intrinsic(&mut self, fs: &mut Fs, f: FuncId, targs: &[Ty], args: &[TArg], ret: &Ty, sp: Span) -> String {
        let fd = self.prog.func(f).clone();
        let pkg = self.prog.packages[fd.pkg as usize].name.clone();
        let key = fd.recv_key.map(|k| self.key_name(k));
        let qn = match &key {
            Some(k) => format!("{}.{}", k, fd.name),
            None => format!("{}.{}", pkg, fd.name),
        };
        let l = self.loc(sp);
        let s: HashMap<TParamId, Ty> = fd.tparams.iter().copied().zip(targs.iter().cloned()).collect();
        let recv_ty = fd.recv.as_ref().map(|r| r.ty.subst(&s));
        // element type helpers
        let elem = |t: &Option<Ty>| -> Ty {
            match t {
                Some(Ty::Vec(e)) | Some(Ty::Slice(e)) | Some(Ty::Option(e)) | Some(Ty::Rc(e)) | Some(Ty::Arc(e)) | Some(Ty::Weak(e)) | Some(Ty::Cell(e)) | Some(Ty::Mutex(e)) | Some(Ty::Chan(e)) => (**e).clone(),
                _ => Ty::Unit,
            }
        };
        match qn.as_str() {
            "prelude.panic" => {
                let a = self.expr(fs, &args[0].e);
                self.emit(fs, &format!("kite_panic_str({}, {});", a, l));
                "0".into()
            }
            "prelude.unreachable" => {
                self.emit(fs, &format!("kite_panic(\"entered unreachable code\", {});", l));
                "0".into()
            }
            "prelude.assert" => {
                let a = self.expr(fs, &args[0].e);
                self.emit(fs, &format!("if (!({})) kite_panic(\"assertion failed\", {});", a, l));
                "0".into()
            }
            "prelude.assertEq" => {
                let t = targs[0].clone();
                let a = self.addr(fs, &args[0].e);
                let b = self.addr(fs, &args[1].e);
                let eq = self.eq_fn(&t);
                let fm = self.fmt_fn(&t);
                let m = self.tmp();
                self.emit(fs, &format!("if (!{}({}, {})) {{ kite_string {} = {{0}}; kite_fmt_cstr(&{}, \"assertion failed: \"); {}(&{}, {}, 1); kite_fmt_cstr(&{}, \" != \"); {}(&{}, {}, 1); kite_panic_buf(&{}, {}); }}", eq, a, b, m, m, fm, m, a, m, fm, m, b, m, l));
                "0".into()
            }
            "prelude.__panicErr" => {
                let t = targs[0].clone();
                let msg = self.expr(fs, &args[0].e);
                let e = self.addr(fs, &args[1].e);
                let fm = self.fmt_fn(&t);
                let m = self.tmp();
                self.emit(fs, &format!("{{ kite_string {} = {{0}}; kite_string_push(&{}, {}); kite_fmt_cstr(&{}, \": \"); {}(&{}, {}, 0); kite_panic_buf(&{}, {}); }}", m, m, msg, m, fm, m, e, m, l));
                "0".into()
            }
            "prelude.swap" => {
                let t = targs[0].clone();
                let c = self.cty(&t);
                let a = self.addr(fs, &args[0].e);
                let b = self.addr(fs, &args[1].e);
                self.emit(fs, &format!("{{ {} *_a = {}, *_b = {}; {} _t = *_a; *_a = *_b; *_b = _t; }}", c, a, b, c));
                "0".into()
            }
            "prelude.replace" => {
                let t = targs[0].clone();
                let c = self.cty(&t);
                let a = self.addr(fs, &args[0].e);
                let v = self.expr(fs, &args[1].e);
                let r = self.tmp();
                self.emit(fs, &format!("{} {} = *{}; *{} = {};", c, r, a, a, v));
                r
            }
            "prelude.take" => {
                let t = targs[0].clone();
                let c = self.cty(&t);
                let a = self.addr(fs, &args[0].e);
                let d = self.default_value(fs, &t);
                let r = self.tmp();
                self.emit(fs, &format!("{} {} = *{}; *{} = {};", c, r, a, a, d));
                r
            }
            "str.len" => {
                let a = self.expr(fs, &args[0].e);
                format!("({}).len", a)
            }
            "String.asStr" => {
                let a = self.addr(fs, &args[0].e);
                format!("kite_string_view({})", a)
            }
            "Slice.len" => {
                let a = self.expr(fs, &args[0].e);
                format!("({}).len", a)
            }
            "Slice.ptr" | "str.ptr" => {
                let a = self.expr(fs, &args[0].e);
                let et = elem(&recv_ty);
                let c = if qn == "str.ptr" { "uint8_t".to_string() } else { self.cty(&et) };
                format!("(({} *)({}).ptr)", c, a)
            }
            "str.bytes" => {
                let a = self.expr(fs, &args[0].e);
                let r = self.tmp();
                self.emit(fs, &format!("kite_str {} = {};", r, a));
                format!("((kite_slice){{ (void *){}.ptr, {}.len }})", r, r)
            }
            "Hasher.write" => {
                let t = targs.last().cloned().unwrap();
                let h = self.expr(fs, &args[0].e);
                let x = self.addr(fs, &args[1].e);
                let hf = self.hash_fn(&t);
                self.emit(fs, &format!("({})->f_state = (({})->f_state ^ {}({})) * 1099511628211ULL;", h, h, hf, x));
                "0".into()
            }
            q if q.starts_with("Vec.") => self.vec_intrinsic(fs, &q[4..], &elem(&recv_ty), args, ret, &l),
            q if q.starts_with("Map.") => {
                let (k, v) = match &recv_ty {
                    Some(Ty::Map(k, v)) => ((**k).clone(), (**v).clone()),
                    _ => unreachable!(),
                };
                self.map_intrinsic(fs, &q[4..], &k, &v, args, ret, &l)
            }
            "Rc.count" | "Arc.count" => {
                let a = self.expr(fs, &args[0].e);
                let e = elem(&recv_ty);
                self.ensure_rcbox(&e);
                if qn == "Arc.count" {
                    format!("__atomic_load_n(&({})->strong, __ATOMIC_SEQ_CST)", a)
                } else {
                    format!("({})->strong", a)
                }
            }
            "Rc.downgrade" => {
                let a = self.expr(fs, &args[0].e);
                let e = elem(&recv_ty);
                self.ensure_rcbox(&e);
                let r = self.tmp();
                let c = self.cty(ret);
                self.emit(fs, &format!("{} {} = {}; {}->weak++;", c, r, a, r));
                r
            }
            "Weak.upgrade" => {
                let a = self.expr(fs, &args[0].e);
                let e = elem(&recv_ty);
                self.ensure_rcbox(&e);
                let c = self.cty(ret);
                let r = self.tmp();
                let set = self.oset(ret, &r, &a);
                self.emit(fs, &format!("{} {} = {{0}}; if (({})->strong > 0) {{ ({})->strong++; {} }}", c, r, a, a, set));
                r
            }
            "Cell.get" => {
                let a = self.lval(fs, &args[0].e);
                let c = self.cty(ret);
                let _ = c;
                self.materialize(fs, &a, ret, false)
            }
            "Cell.set" => {
                let v = self.expr(fs, &args[1].e);
                let a = self.lval(fs, &args[0].e);
                self.emit(fs, &format!("{} = {};", a, v));
                "0".into()
            }
            "Mutex.lock" | "MutexRef.lock" => {
                let (m, v) = self.lock_target(fs, &args[0].e);
                self.emit(fs, &format!("kite_mutex_lock({}->mu);", m));
                self.register_stmt(fs, Cl::Unlock(format!("{}->mu", m)));
                format!("({})", v)
            }
            "Chan.send" => {
                let e = elem(&recv_ty);
                let c = self.expr(fs, &args[0].e);
                let v = self.expr(fs, &args[1].e);
                let ec = self.cty(&e);
                let t = self.tmp();
                let d = self.cancelled_send_drop(&e, &t);
                self.emit(fs, &format!("{} {} = {}; if (!kite_chan_send({}, &{}, {})) {{{}}}", ec, t, v, c, t, l, d));
                "0".into()
            }
            "Chan.recv" => {
                let c = self.expr(fs, &args[0].e);
                let oc = self.cty(ret);
                let r = self.tmp();
                if self.niche(ret) {
                    self.emit(fs, &format!("{} {} = {{0}}; if (!kite_chan_recv({}, &{})) {} = NULL;", oc, r, c, r, r));
                } else {
                    self.emit(fs, &format!("{} {} = {{0}}; {}.some = kite_chan_recv({}, &{}.val);", oc, r, r, c, r));
                }
                r
            }
            "Chan.close" => {
                let c = self.expr(fs, &args[0].e);
                self.emit(fs, &format!("kite_chan_close({}, {});", c, l));
                "0".into()
            }
            "Chan.len" => {
                let c = self.expr(fs, &args[0].e);
                format!("kite_chan_len({})", c)
            }
            "math.sqrt" | "math.pow" | "math.floor" | "math.ceil" | "math.round" | "math.sin" | "math.cos" | "math.tan" | "math.atan2" | "math.log" | "math.exp" => {
                let vs = self.arg_vals(fs, args);
                format!("{}({})", &qn[5..], vs.join(", "))
            }
            "math.abs" => {
                let vs = self.arg_vals(fs, args);
                format!("fabs({})", vs[0])
            }
            "math.isNaN" => {
                let vs = self.arg_vals(fs, args);
                format!("isnan({})", vs[0])
            }
            "math.inf" => "INFINITY".into(),
            "os.exit" => {
                let vs = self.arg_vals(fs, args);
                self.emit(fs, &format!("kite_os_exit({});", vs[0]));
                "0".into()
            }
            _ => {
                // runtime function with the standard ABI
                let cname = match &key {
                    Some(k) => format!("kite_{}_{}", k, fd.name),
                    None => format!("kite_{}_{}", pkg, fd.name),
                };
                let mut modes = vec![];
                let mut tys = vec![];
                if let Some(r) = &fd.recv {
                    modes.push(r.mode);
                    tys.push(r.ty.subst(&s));
                }
                for p in &fd.params {
                    modes.push(p.mode);
                    tys.push(p.ty.subst(&s));
                }
                let avs = self.args(fs, args, &modes, &tys);
                let call = format!("{}({})", cname, avs.join(", "));
                self.finish_call(fs, call, ret)
            }
        }
    }

    /// Pointer to the Mutex struct behind a (possibly arc-wrapped) receiver expression.
    /// The Mutex struct behind a lock projection's receiver, and a pointer to
    /// the guarded value.
    fn lock_target(&mut self, fs: &mut Fs, e: &TExpr) -> (String, String) {
        let recv = match &e.kind {
            TK::Proj { call, .. } => match &call.kind {
                TK::Call { args, .. } => args[0].e.clone(),
                _ => e.clone(),
            },
            _ => e.clone(),
        };
        let mt = self.sub(fs, &recv.ty);
        let c = self.cty(&mt);
        let p = self.lval(fs, &recv);
        let m = self.tmp();
        self.emit(fs, &format!("{} *{} = &{};", c, m, p));
        let v = if matches!(mt, Ty::MutexRef(_)) { format!("{}->ptr", m) } else { format!("&{}->val", m) };
        (m, v)
    }


    fn vec_intrinsic(&mut self, fs: &mut Fs, name: &str, el: &Ty, args: &[TArg], ret: &Ty, l: &str) -> String {
        let ec = self.cty(el);
        let v = self.addr(fs, &args[0].e);
        let vp = self.tmp();
        self.emit(fs, &format!("kite_vec *{} = {};", vp, v));
        let arr = format!("(({} *){}->ptr)", ec, vp);
        match name {
            "push" => {
                let x = self.expr(fs, &args[1].e);
                let t = self.tmp();
                self.emit(fs, &format!("{} {} = {}; kite_vec_reserve({}, 1, sizeof({})); {}[{}->len++] = {};", ec, t, x, vp, ec, arr, vp, t));
                "0".into()
            }
            "pop" => {
                let oc = self.cty(ret);
                let r = self.tmp();
                let set = self.oset(ret, &r, &format!("{}[--{}->len]", arr, vp));
                self.emit(fs, &format!("{} {} = {{0}}; if ({}->len) {{ {} }}", oc, r, vp, set));
                r
            }
            "insert" => {
                let i = self.expr(fs, &args[1].e);
                let x = self.expr(fs, &args[2].e);
                let it = self.tmp();
                let t = self.tmp();
                self.emit(fs, &format!("int64_t {} = {}; {} {} = {};", it, i, ec, t, x));
                self.emit(fs, &format!("if ({} < 0 || {} > {}->len) kite_panic_index({}, {}->len, {});", it, it, vp, it, vp, l));
                self.emit(fs, &format!("kite_vec_reserve({}, 1, sizeof({})); memmove({} + {} + 1, {} + {}, (size_t)({}->len - {}) * sizeof({})); {}[{}] = {}; {}->len++;", vp, ec, arr, it, arr, it, vp, it, ec, arr, it, t, vp));
                "0".into()
            }
            "remove" | "swapRemove" => {
                let i = self.expr(fs, &args[1].e);
                let it = self.tmp();
                let r = self.tmp();
                self.emit(fs, &format!("int64_t {} = kite_idx({}, {}->len, {}); {} {} = {}[{}];", it, i, vp, l, ec, r, arr, it));
                if name == "remove" {
                    self.emit(fs, &format!("memmove({} + {}, {} + {} + 1, (size_t)({}->len - {} - 1) * sizeof({})); {}->len--;", arr, it, arr, it, vp, it, ec, vp));
                } else {
                    self.emit(fs, &format!("{}[{}] = {}[{}->len - 1]; {}->len--;", arr, it, arr, vp, vp));
                }
                r
            }
            "clear" | "truncate" => {
                let n = if name == "truncate" { self.expr(fs, &args[1].e) } else { "0".into() };
                let nt = self.tmp();
                self.emit(fs, &format!("int64_t {} = {};", nt, n));
                if self.needs_drop(el) {
                    let d = self.drop_fn(el);
                    self.emit(fs, &format!("for (int64_t _i = {} < 0 ? 0 : {}; _i < {}->len; _i++) {}(&{}[_i]);", nt, nt, vp, d, arr));
                }
                self.emit(fs, &format!("if ({} >= 0 && {} < {}->len) {}->len = {};", nt, nt, vp, vp, nt));
                "0".into()
            }
            "extend" => {
                let o = self.expr(fs, &args[1].e);
                let ot = self.tmp();
                self.emit(fs, &format!("kite_vec {} = {}; kite_vec_reserve({}, {}.len, sizeof({})); if ({}.len) memcpy({} + {}->len, {}.ptr, (size_t){}.len * sizeof({})); {}->len += {}.len; free({}.ptr);", ot, o, vp, ot, ec, ot, arr, vp, ot, ot, ec, vp, ot, ot));
                "0".into()
            }
            "reverse" => {
                self.emit(fs, &format!("for (int64_t _i = 0, _j = {}->len - 1; _i < _j; _i++, _j--) {{ {} _t = {}[_i]; {}[_i] = {}[_j]; {}[_j] = _t; }}", vp, ec, arr, arr, arr, arr));
                "0".into()
            }
            "swap" => {
                let i = self.expr(fs, &args[1].e);
                let j = self.expr(fs, &args[2].e);
                self.emit(fs, &format!("{{ int64_t _i = kite_idx({}, {}->len, {}), _j = kite_idx({}, {}->len, {}); {} _t = {}[_i]; {}[_i] = {}[_j]; {}[_j] = _t; }}", i, vp, l, j, vp, l, ec, arr, arr, arr, arr));
                "0".into()
            }
            "reserve" => {
                let n = self.expr(fs, &args[1].e);
                self.emit(fs, &format!("if ({} > 0) kite_vec_reserve({}, {}, sizeof({}));", n, vp, n, ec));
                "0".into()
            }
            "cap" => format!("{}->cap", vp),
            "sort" => {
                let f = self.sort_fn(el);
                self.emit(fs, &format!("{}(({} *){}->ptr, {}->len);", f, ec, vp, vp));
                "0".into()
            }
            "sortBy" => {
                let f = self.addr(fs, &args[1].e);
                let w = format!("sortby_{}", self.mangle(el));
                if self.helpers.insert(w.clone()) {
                    let pc = self.param_cty(Mode::Borrow, el);
                    let (aa, bb) = if self.is_copy(el) { (format!("*({} *)a", ec), format!("*({} *)b", ec)) } else { (format!("({} *)a", ec), format!("({} *)b", ec)) };
                    let _ = writeln!(self.protos, "static int {}(const void *a, const void *b, void *c);", w);
                    let _ = writeln!(self.bodies, "static int {}(const void *a, const void *b, void *c) {{\n    kite_func *f = c;\n    bool (*fn)(void *, {}, {}) = (bool (*)(void *, {}, {}))f->fn;\n    if (fn(f->env, {}, {})) return -1;\n    if (fn(f->env, {}, {})) return 1;\n    return 0;\n}}", w, pc, pc, pc, pc, aa, bb, bb, aa);
                }
                self.emit(fs, &format!("kite_sort({}->ptr, {}->len, sizeof({}), {}, {});", vp, vp, ec, w, f));
                "0".into()
            }
            _ => panic!("unknown Vec intrinsic {}", name),
        }
    }

    fn map_intrinsic(&mut self, fs: &mut Fs, name: &str, k: &Ty, v: &Ty, args: &[TArg], ret: &Ty, _l: &str) -> String {
        let (ent, desc) = self.map_ent(k, v);
        let mp = self.addr(fs, &args[0].e);
        let m = self.tmp();
        self.emit(fs, &format!("kite_map *{} = {};", m, mp));
        match name {
            "len" => format!("{}->len", m),
            "get" | "getMut" | "contains" => {
                let kp = self.borrow_ptr(fs, &args[1].e);
                let e = self.tmp();
                self.emit(fs, &format!("{} *{} = mf_{}({}, {});", ent, e, desc, m, kp));
                if name == "contains" {
                    format!("({} != NULL)", e)
                } else {
                    format!("({} ? &{}->v : NULL)", e, e)
                }
            }
            "insert" => {
                let kv = self.expr(fs, &args[1].e);
                let vv = self.expr(fs, &args[2].e);
                self.map_insert(fs, &m, k, v, &kv, &vv)
            }
            "remove" => {
                let kp = self.borrow_ptr(fs, &args[1].e);
                let oc = self.cty(ret);
                let r = self.tmp();
                let tmpe = self.tmp();
                self.emit(fs, &format!("{} {} = {{0}}; {} {};", oc, r, ent, tmpe));
                let dk = if self.needs_drop(k) {
                    let d = self.drop_fn(k);
                    format!(" {}(&{}.k);", d, tmpe)
                } else {
                    String::new()
                };
                let set = self.oset(ret, &r, &format!("{}.v", tmpe));
                self.emit(fs, &format!("if (mr_{}({}, {}, &{})) {{ {}{} }}", desc, m, kp, tmpe, set, dk));
                r
            }
            "entry" => {
                let kv = self.expr(fs, &args[1].e);
                let kc = self.cty(k);
                let tk = self.tmp();
                let ex = self.tmp();
                let e = self.tmp();
                self.emit(fs, &format!("{} {} = {}; bool {};", kc, tk, kv, ex));
                self.emit(fs, &format!("{} *{} = ms_{}({}, &{}, &{});", ent, e, desc, m, tk, ex));
                let dv = self.default_value(fs, v);
                let dk = if self.needs_drop(k) {
                    let d = self.drop_fn(k);
                    format!("{}(&{});", d, tk)
                } else {
                    String::new()
                };
                self.emit(fs, &format!("if (!{}) {{ {}->k = {}; {}->v = {}; }} else {{ {} }}", ex, e, tk, e, dv, dk));
                format!("(&{}->v)", e)
            }
            "clear" => {
                let d = self.drop_fn(&Ty::Map(std::rc::Rc::new(k.clone()), std::rc::Rc::new(v.clone())));
                self.emit(fs, &format!("{}({}); memset({}, 0, sizeof(kite_map));", d, m, m));
                "0".into()
            }
            _ => panic!("unknown Map intrinsic {}", name),
        }
    }

