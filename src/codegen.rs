    fn try_expr(&mut self, fs: &mut Fs, x: &TExpr, wrap: Option<&TryWrap>, t: &Ty, _sp: Span) -> String {
        let xt = self.sub(fs, &x.ty);
        let v = self.expr(fs, x);
        let xc = self.cty(&xt);
        let tv = self.tmp();
        self.emit(fs, &format!("{} {} = {};", xc, tv, v));
        let ret = fs.ret.clone();
        let rc = self.cty(&ret);
        match &xt {
            Ty::Option(_) => {
                let cond = self.osome(&xt, &tv);
                self.emit(fs, &format!("if (!{}) {{", cond));
                fs.ind += 1;
                let none = format!("(({}){{0}})", rc);
                self.emit_return(fs, &none);
                fs.ind -= 1;
                self.emit(fs, "}");
                if *t == Ty::Unit {
                    "0".into()
                } else {
                    self.oval(&xt, &tv)
                }
            }
            Ty::Result(_, e1) => {
                let e1 = (**e1).clone();
                self.emit(fs, &format!("if (!{}.ok) {{", tv));
                fs.ind += 1;
                let errv = match wrap {
                    None => format!("{}.u.err", tv),
                    Some(TryWrap::ToError) => {
                        let et = match &ret {
                            Ty::Result(_, e) => (**e).clone(),
                            _ => unreachable!(),
                        };
                        let vt = self.vtable(&e1, &et);
                        let ec = self.cty(&e1);
                        let b = self.tmp();
                        self.emit(fs, &format!("{} *{} = kite_box_alloc(sizeof({})); *{} = {}.u.err;", ec, b, ec, b, tv));
                        format!("((kite_iface){{ {}, &{} }})", b, vt)
                    }
                    Some(TryWrap::Call(hid, w)) => {
                        let ec = self.cty(&e1);
                        let n = self.local_cname(fs, *hid);
                        self.emit(fs, &format!("{} {} = {}.u.err;", ec, n, tv));
                        fs.repr.insert(*hid, Repr::Val(n));
                        self.push_scope(fs, SK::Stmt);
                        let wv = self.expr(fs, w);
                        let wt = self.sub(fs, &w.ty);
                        let r = self.materialize(fs, &wv, &wt, false);
                        fs.scopes.pop();
                        r
                    }
                };
                let r = self.tmp();
                self.emit(fs, &format!("{} {} = {{ .ok = 0, .u.err = {} }};", rc, r, errv));
                self.emit_return(fs, &r);
                fs.ind -= 1;
                self.emit(fs, "}");
                if *t == Ty::Unit {
                    "0".into()
                } else {
                    format!("{}.u.val", tv)
                }
            }
            _ => v,
        }
    }

